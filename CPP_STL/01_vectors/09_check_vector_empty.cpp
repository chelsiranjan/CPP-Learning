// .empty() function returns 1 (true) if the vector is empty a
// 0 (false) if it contains one or more elements


#include <iostream>
#include <vector>
using namespace std;

int main() {
  vector<string> cars;
  cout << cars.empty();  // Outputs 1 (The vector is empty)
  return 0;
}


